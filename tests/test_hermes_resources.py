    monitor.write_text(f"#!/bin/sh\nprintf invoked > '{marker}'\n")
    monitor.chmod(0o700)
    subprocess.run(
        ["git", "-C", str(cwd), "config", "core.fsmonitor", str(monitor)],
        check=True,
        capture_output=True,
    )
    (cwd / "pyproject.toml").write_text("[project]\nname = 'fixture'\n")
    snapshot = tmp_path / "snapshot"
    snapshot.mkdir()
    result = resources.load_resources(
        snapshot,
        cwd,
        {"enabled_tools": ["read_file"], "include_runtime_context": False},
    )
    assert "Workspace (snapshot at session start" in result.system_prompt
    assert "- Project: pyproject.toml" in result.system_prompt
    assert not marker.exists()


