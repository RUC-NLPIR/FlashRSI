@pytest.mark.parametrize("case", ASSEMBLY, ids=lambda case: case["name"])
def test_prompt_core_matches_real_complete_upstream_assembly(tmp_path, case):
    import shutil
    import subprocess

    import yaml

    inputs = case["inputs"]
    root = tmp_path / case["name"]
    snapshot, cwd = root / "profile", root / "work"
    snapshot.mkdir(parents=True)
    cwd.mkdir()
    (snapshot / "SOUL.md").write_text(inputs["soul"])
    (snapshot / "config.yaml").write_text(yaml.safe_dump(inputs["config"]))
    for name, content in inputs["project_files"].items():
        (cwd / name).write_text(content)
    for name, content in inputs["skill_files"].items():
        path = snapshot / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    if inputs.get("git_branch"):
        if not shutil.which("git"):
            pytest.skip("Git workspace fixture requires git")
        subprocess.run(
            ["git", "init", "--initial-branch", inputs["git_branch"], str(cwd)],
            check=True,
            capture_output=True,
        )
    result = resources.load_resources(
        snapshot, cwd, {**inputs["config"], "include_runtime_context": False}
    )
    normalized = result.system_prompt.replace(str(tmp_path.resolve()), "<FIXTURE_ROOT>")
    assert normalized == case["expected_prompt_core"]


def test_automatic_workspace_git_probe_does_not_execute_repo_fsmonitor(tmp_path):
    import shutil
    import subprocess

    if not shutil.which("git"):
        pytest.skip("Git workspace fixture requires git")
    cwd = tmp_path / "task"
