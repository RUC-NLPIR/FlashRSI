    from zoneinfo import ZoneInfo

    from flashrsi.agents.hermes.runtime.hermes_native.runtime_context import (
        runtime_context,
    )

    now = datetime.fromisoformat(case["now"]).astimezone(
        ZoneInfo(case["settings"]["timezone"])
    )
    actual = runtime_context(Path("/profile"), Path("/task"), case["settings"], now=now)
    # Task scratch artifacts persist here; upstream's process/worktree pruning
    # service is outside this runtime, so do not promise its 24h policy.
    expected = [
        value.replace("; entries idle for 24h are pruned", "")
        for value in case["expected"]
    ]
    assert list(actual) == expected


