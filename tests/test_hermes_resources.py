def _skill(root, path, name, description="Useful workflow", **metadata):
    import yaml

    target = root / "skills" / path / "SKILL.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    frontmatter = {"name": name, "description": description, **metadata}
    target.write_text(
        "---\n" + yaml.safe_dump(frontmatter) + "---\n# Workflow\nDo the task.\n"
    )
    return target


def test_skills_preserve_ambiguous_copy_paths_and_prune_support_directories(tmp_path):
    _skill(tmp_path, "coding/first", "same")
    _skill(tmp_path, "coding/second", "same", description="Different workflow")
    _skill(tmp_path, "coding/first/references/nested", "not-a-standalone-skill")
    _skill(tmp_path, ".archive/old", "archived")
    assert [s.name for s in resources.discover_skills(tmp_path)] == [
        "coding/first",
        "coding/second",
    ]
    catalog = json.loads(resources.skills_list(tmp_path))
    assert catalog["count"] == 2
    assert catalog["categories"] == ["coding"]
    assert not json.loads(resources.skill_view(tmp_path, "same"))["success"]
    assert json.loads(resources.skill_view(tmp_path, "coding/first"))["success"]


def test_skill_view_progressive_files_and_path_containment(tmp_path):
    skill = _skill(tmp_path, "sample", "sample", tags=["local", "python"])
    linked = skill.parent / "references/api.md"
    linked.parent.mkdir()
    linked.write_text("API reference")
    main = json.loads(resources.skill_view(tmp_path, "sample"))
    assert main["tags"] == ["local", "python"]
    assert main["linked_files"] == {"references": ["references/api.md"]}
    assert main["readiness_status"] == "available"
    assert "metadata" not in main
    loaded = json.loads(resources.skill_view(tmp_path, "sample", "references/api.md"))
    assert loaded["content"] == "API reference"
    assert loaded["file_type"] == ".md"
    assert not json.loads(resources.skill_view(tmp_path, "sample", "../SOUL.md"))[
        "success"
    ]
    outside = tmp_path / "outside.txt"
    outside.write_text("Not part of the skill")
    (skill.parent / "escape.md").symlink_to(outside)
    assert not json.loads(resources.skill_view(tmp_path, "sample", "escape.md"))[
        "success"
    ]


