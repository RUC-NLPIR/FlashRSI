def test_model_window_controls_actual_soul_and_project_context_budget(tmp_path):
    snapshot, cwd = tmp_path / "snapshot", tmp_path / "work"
    snapshot.mkdir()
    cwd.mkdir()
    (snapshot / "SOUL.md").write_text("S" * 50_000)
    (cwd / "AGENTS.md").write_text("A" * 50_000)
    options = {
        "enabled_tools": [],
        "include_runtime_context": False,
        "llm": {"model_name": "window-test", "context_length": 128_000},
    }
    narrow = resources.load_resources(snapshot, cwd, options)
    assert "kept 21504+6144 of 50000" in narrow.system_prompt
    assert "truncated AGENTS.md" in narrow.system_prompt
    assert len(narrow.diagnostics) == 2
    options["llm"]["context_length"] = 1_000_000
    broad = resources.load_resources(snapshot, cwd, options)
    assert "S" * 50_000 in broad.system_prompt
    assert "A" * 50_000 in broad.system_prompt
    assert "truncated" not in broad.system_prompt
    assert not broad.diagnostics
    forced = resources.load_resources(
        snapshot, cwd, {**options, "context_file_max_chars": 100}
    )
    assert "kept 70+20 of 50000" in forced.system_prompt


